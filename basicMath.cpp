// This program displays various math equations

#include <iostream>
#include <cmath>

int main() {
    std::cout << "6+6 = " << 6 + 6 << std::endl;  // addition
    std::cout << "6-3 = " << 6 - 3 << std::endl;  // subtraction
    std::cout << "6*6 = " << 6 * 6 << std::endl;  // multiplication
    std::cout << "8/4 = " << 8 / 4 << std::endl;  // integer division
    std::cout << "16/6 = " << 16 / 6 << std::endl;  // decimal division
    std::cout << "12 % 5 = " << 12 % 5 << std::endl;  // modulo
    std::cout << "5^2 = " << pow(5, 2) << std::endl;  // exponents
    std::cout << "18^0.4 = " << pow(18, 0.4) << std::endl;  // exponents
    std::cout << "√6 = " << sqrt(6) << std::endl;           // square root
}
